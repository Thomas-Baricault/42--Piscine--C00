#include <unistd.h>

void	ft_print_comb(void)
{
	char	s[3];

	s[0] = '0';
	while (s[0] <= '9')
	{
		s[1] = s[0] + 1;
		while (s[1] <= '9')
		{
			s[2] = s[1] + 1;
			while (s[2] <= '9')
			{
				write(1, s, 3);
				if (!(s[0] == '7' && s[1] == '8' && s[2] == '9'))
				{
					write(1, ", ", 2);
				}
				s[2]++;
			}
			s[1]++;
		}
		s[0]++;
	}
	return ;
}
