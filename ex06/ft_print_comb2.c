#include <unistd.h>

void	add(char *s)
{
	if (s[1] == '9')
	{
		s[0]++;
		s[1] = '0';
	}
	else
	{
		s[1]++;
	}
}

void	ft_print_comb2(void)
{
	char	s[4];

	s[0] = '0';
	s[1] = '0';
	while (!(s[0] == '9' && s[1] == '9'))
	{
		s[2] = s[0];
		s[3] = s[1];
		add(s + 2);
		while (s[2] <= '9')
		{
			write(1, s, 2);
			write(1, " ", 1);
			write(1, s + 2, 2);
			if (!(s[0] == '9' && s[1] == '8' && s[2] == '9' && s[3] == '9'))
			{
				write(1, ", ", 2);
			}
			add(s + 2);
		}
		add(s);
	}
	return ;
}
